def almighty(a, b, c):
    x = (-b + (b**2 - 4*a*c)**0.5) / (2*a)
    y = (-b - (b**2 - 4*a*c)**0.5) / (2*a)
    print(f"The Values of x and y are \nX={x}\nY={y}")
almighty(1, -5, 6)
print("Where X is the Positive value of the Almighty Formula \nAnd Y is the Negative value")
